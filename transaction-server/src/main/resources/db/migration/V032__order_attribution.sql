-- 归因快照永久绑定原请求与单次令牌；不回填旧订单，不修改已执行迁移。
CREATE TABLE tc_order_attribution (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '快照内部主键',
  tenant_id BIGINT UNSIGNED NOT NULL COMMENT '认证租户',
  order_id BIGINT UNSIGNED NOT NULL COMMENT '永久绑定的订单主键',
  order_no VARCHAR(64) NOT NULL COMMENT '原成功订单号',
  actor_key CHAR(64) NOT NULL COMMENT '原请求认证主体摘要',
  operation VARCHAR(64) NOT NULL COMMENT '原命令操作名',
  request_key VARCHAR(128) NOT NULL COMMENT '原命令幂等键',
  request_hash CHAR(64) NOT NULL COMMENT '包含完整令牌摘要及地址字段的原请求摘要',
  issuer VARCHAR(255) NOT NULL COMMENT '固定可信营销签发方',
  jti VARCHAR(64) NOT NULL COMMENT '签发方单次令牌身份，取消退款不释放',
  member_id BIGINT UNSIGNED NOT NULL COMMENT '冻结会员主键',
  quote_id BIGINT UNSIGNED NOT NULL COMMENT '冻结报价主键',
  referral_ref VARCHAR(64) NOT NULL COMMENT '不可变归因引用，不代表已满足奖励资格',
  campaign_id VARCHAR(64) NOT NULL COMMENT '原平台活动标识',
  definition_version BIGINT UNSIGNED NOT NULL COMMENT '已签名活动定义版本',
  token_hash CHAR(64) NOT NULL COMMENT '完整令牌摘要，不保存原令牌',
  issued_at DATETIME(3) NOT NULL COMMENT '令牌签发UTC时间',
  expires_at DATETIME(3) NOT NULL COMMENT '令牌到期UTC时间',
  created_at DATETIME(3) NOT NULL COMMENT '消费提交UTC时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_attribution_order (tenant_id,order_id),
  UNIQUE KEY uk_attribution_token (tenant_id,issuer,jti),
  UNIQUE KEY uk_attribution_command (tenant_id,actor_key,operation,request_key),
  CONSTRAINT fk_attribution_order FOREIGN KEY (tenant_id,order_id) REFERENCES tc_order(tenant_id,id),
  CONSTRAINT chk_attribution_version CHECK (definition_version>0),
  CONSTRAINT chk_attribution_binding CHECK (member_id>0 AND quote_id>0 AND operation='order.create'),
  CONSTRAINT chk_attribution_text CHECK (CHAR_LENGTH(jti)>0 AND CHAR_LENGTH(referral_ref)>0 AND CHAR_LENGTH(campaign_id)>0),
  CONSTRAINT chk_attribution_time CHECK (issued_at<=created_at AND created_at<expires_at AND expires_at<=issued_at+INTERVAL 15 MINUTE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='订单永久归因快照、单次消费及原成功请求回放凭证';
