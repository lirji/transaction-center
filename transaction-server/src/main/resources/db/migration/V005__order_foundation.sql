-- 商户身份由租户管理员显式配置，不以默认测试商户承接真实订单。
CREATE TABLE tc_merchant (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '商户配置内部主键',
  tenant_id BIGINT UNSIGNED NOT NULL COMMENT '所属租户，首期每租户一个交易商户',
  merchant_no VARCHAR(64) NOT NULL COMMENT '不可变逻辑商户编号，渠道商户映射另行配置',
  name VARCHAR(200) NOT NULL COMMENT '商户展示名称',
  status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE允许新订单，FROZEN禁止新订单但不阻断历史资金处理',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建UTC时间',
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最近更新UTC时间',
  version BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '配置乐观版本',
  PRIMARY KEY (id),
  UNIQUE KEY uk_merchant_tenant (tenant_id),
  UNIQUE KEY uk_merchant_tenant_id (tenant_id,id),
  CHECK (status IN ('ACTIVE','FROZEN'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='租户交易商户配置表，不包含渠道密钥';

CREATE TABLE tc_order (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '订单内部主键，对外作为字符串返回',
  tenant_id BIGINT UNSIGNED NOT NULL COMMENT '所属租户，所有查询和更新必须限定',
  order_no VARCHAR(64) NOT NULL COMMENT '不可变订单业务编号',
  member_id BIGINT UNSIGNED NOT NULL COMMENT '购买会员主键',
  quote_id BIGINT UNSIGNED NOT NULL COMMENT '来源报价，首期每报价仅能创建一单',
  merchant_id BIGINT UNSIGNED NOT NULL COMMENT '逻辑收款商户配置主键',
  merchant_no VARCHAR(64) NOT NULL COMMENT '创建时冻结的逻辑商户编号',
  warehouse_id BIGINT UNSIGNED NULL COMMENT '实物订单单仓主键，纯服务订单为空',
  status VARCHAR(24) NOT NULL COMMENT '履约状态，与财务状态分离',
  financial_status VARCHAR(24) NOT NULL COMMENT 'UNPAID未付，NO_PAYMENT_REQUIRED零元，后续支付退款状态',
  gross_amount BIGINT UNSIGNED NOT NULL COMMENT '冻结商品原价合计',
  discount_amount BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '优惠合计，首期固定为零',
  freight_amount BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '运费，首期不另收取',
  tax_amount BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '额外税额，首期不另收取',
  payable_amount BIGINT UNSIGNED NOT NULL COMMENT '冻结订单应付币种最小单位',
  currency CHAR(3) NOT NULL COMMENT '冻结订单单一币种',
  expires_at DATETIME(3) NOT NULL COMMENT '支付截止检查时间，不代表可直接释放库存',
  payment_started_at DATETIME(3) NULL COMMENT '首次支付尝试许可时间，非空时取消必须经过支付关单协议',
  paid_at DATETIME(3) NULL COMMENT '有效收款本地确认时间，零元订单保持空',
  completed_at DATETIME(3) NULL COMMENT '商业完成UTC时间，与支付时间不同',
  cancelled_at DATETIME(3) NULL COMMENT '可靠取消UTC时间',
  cancel_reason VARCHAR(255) NULL COMMENT '取消业务原因',
  referral_ref VARCHAR(128) NULL COMMENT '未来营销验签确认的归因引用，未接通时保持空',
  created_at DATETIME(3) NOT NULL COMMENT '创建UTC时间',
  updated_at DATETIME(3) NOT NULL COMMENT '最近状态变更UTC时间',
  version BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '订单证据及状态版本',
  PRIMARY KEY (id),
  UNIQUE KEY uk_order_tenant_id (tenant_id,id),
  UNIQUE KEY uk_order_no (tenant_id,order_no),
  UNIQUE KEY uk_order_quote (tenant_id,quote_id),
  KEY ix_order_member (tenant_id,member_id,id),
  KEY ix_order_deadline (status,expires_at,id),
  FOREIGN KEY (tenant_id,member_id) REFERENCES tc_member (tenant_id,id),
  FOREIGN KEY (tenant_id,quote_id) REFERENCES tc_quote (tenant_id,id),
  FOREIGN KEY (tenant_id,merchant_id) REFERENCES tc_merchant (tenant_id,id),
  FOREIGN KEY (tenant_id,warehouse_id) REFERENCES tc_warehouse (tenant_id,id),
  CHECK (status IN ('PENDING_PAYMENT','CLOSING','CANCELLED','PAID','FULFILLING','COMPLETED')),
  CHECK (financial_status IN ('UNPAID','NO_PAYMENT_REQUIRED','PAID','PARTIALLY_REFUNDED','REFUNDED')),
  CHECK (payable_amount <= 9007199254740991 AND discount_amount <= gross_amount),
  CHECK (payable_amount = gross_amount - discount_amount + freight_amount + tax_amount)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='交易订单主表，履约与资金状态分离';

CREATE TABLE tc_order_item (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '订单明细主键',
  tenant_id BIGINT UNSIGNED NOT NULL COMMENT '所属租户',
  order_id BIGINT UNSIGNED NOT NULL COMMENT '所属订单主键',
  sku_id BIGINT UNSIGNED NOT NULL COMMENT '商品SKU主键',
  sku_revision BIGINT UNSIGNED NOT NULL COMMENT '来源报价冻结的发布版本',
  title VARCHAR(200) NOT NULL COMMENT '商品名称快照',
  specification JSON NOT NULL COMMENT '规格键值快照',
  stock_type VARCHAR(16) NOT NULL COMMENT 'PHYSICAL实物预占，SERVICE服务不占库存',
  quantity BIGINT UNSIGNED NOT NULL COMMENT '冻结购买数量',
  unit_price BIGINT UNSIGNED NOT NULL COMMENT '冻结单价最小单位',
  gross_amount BIGINT UNSIGNED NOT NULL COMMENT '冻结明细原价金额',
  discount_amount BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '冻结明细优惠金额，首期为零',
  payable_amount BIGINT UNSIGNED NOT NULL COMMENT '冻结明细应付金额',
  reservation_key VARCHAR(128) NULL COMMENT '实物库存稳定预占键，服务明细为空',
  created_at DATETIME(3) NOT NULL COMMENT '创建UTC时间',
  updated_at DATETIME(3) NOT NULL COMMENT '最近更新UTC时间',
  version BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '明细版本，商品快照不可变',
  PRIMARY KEY (id),
  UNIQUE KEY uk_order_item_tenant_id (tenant_id,id),
  UNIQUE KEY uk_order_item_sku (tenant_id,order_id,sku_id),
  UNIQUE KEY uk_order_item_reservation (tenant_id,reservation_key),
  FOREIGN KEY (tenant_id,order_id) REFERENCES tc_order (tenant_id,id),
  FOREIGN KEY (tenant_id,sku_id,sku_revision) REFERENCES tc_sku_revision (tenant_id,sku_id,revision),
  CHECK (quantity > 0 AND quantity <= 1000000000),
  CHECK (gross_amount = unit_price * quantity AND payable_amount = gross_amount - discount_amount),
  CHECK (payable_amount <= 9007199254740991 AND discount_amount <= gross_amount),
  CHECK ((stock_type='PHYSICAL' AND reservation_key IS NOT NULL) OR (stock_type='SERVICE' AND reservation_key IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='订单明细不可变商品与价格快照';

CREATE TABLE tc_order_address (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '地址快照内部主键',
  tenant_id BIGINT UNSIGNED NOT NULL COMMENT '所属租户，同时绑定加密关联数据',
  order_id BIGINT UNSIGNED NOT NULL COMMENT '所属订单主键',
  recipient_cipher VARBINARY(512) NOT NULL COMMENT '收件人AES-GCM密文，含随机Nonce及认证标签',
  phone_cipher VARBINARY(512) NOT NULL COMMENT '联系电话AES-GCM密文',
  address_cipher BLOB NOT NULL COMMENT '完整地址AES-GCM密文',
  key_version VARCHAR(64) NOT NULL COMMENT '加密密钥版本，不存储密钥内容',
  created_at DATETIME(3) NOT NULL COMMENT '创建UTC时间',
  updated_at DATETIME(3) NOT NULL COMMENT '最近更新UTC时间',
  version BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '地址快照版本',
  PRIMARY KEY (id),
  UNIQUE KEY uk_order_address (tenant_id,order_id),
  FOREIGN KEY (tenant_id,order_id) REFERENCES tc_order (tenant_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='实物订单收货地址密文快照，禁止明文落库';
