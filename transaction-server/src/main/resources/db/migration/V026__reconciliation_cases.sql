CREATE TABLE tc_reconciliation_case (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '内部主键',
 tenant_id BIGINT UNSIGNED NOT NULL COMMENT '所属租户',
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '本地首次受理UTC时间',
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '最近状态变更UTC时间',
 version BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '并发版本',
 case_no CHAR(36) NOT NULL COMMENT '永久差异UUID',
 source_id VARCHAR(64) NOT NULL COMMENT '受信逻辑来源，由服务端绑定',
 channel_id BIGINT UNSIGNED NOT NULL COMMENT '原商户渠道绑定主键',
 statement_date DATE NOT NULL COMMENT '渠道账单日期，时区由渠道合同定义',
 external_line_key VARCHAR(128) NOT NULL COMMENT '原账单稳定行键',
 revision BIGINT UNSIGNED NOT NULL COMMENT '来源账单修订版本',
 difference_type VARCHAR(32) NOT NULL COMMENT '长款短款金额状态或手续费差异',
 reference_type VARCHAR(32) NULL COMMENT '支付请求收款或资金退款引用类型',
 business_ref VARCHAR(64) NULL COMMENT '原渠道请求号收款号或资金退款号',
 evidence_hash CHAR(64) NOT NULL COMMENT '不可变证据SHA256摘要',
 evidence_ref VARCHAR(255) NOT NULL COMMENT '可信证据稳定引用，不在此下载',
 prior_case_no CHAR(36) NULL COMMENT '同账单行较早版本差异编号',
 content_hash CHAR(64) NOT NULL COMMENT '不含传输事件ID的完整业务正文摘要',
 status VARCHAR(16) NOT NULL DEFAULT 'OPEN' COMMENT '待核对处理中或已关闭',
 resolution_ref VARCHAR(128) NULL COMMENT '后续受控处置关联，不等于资金成功',
 PRIMARY KEY(id),
 UNIQUE KEY uk_recon_case_no(tenant_id,case_no),
 UNIQUE KEY uk_recon_business(tenant_id,source_id,channel_id,statement_date,external_line_key,revision,difference_type),
 KEY ix_recon_queue(tenant_id,status,id),
 CHECK (status IN ('OPEN','PROCESSING','CLOSED')),
 CHECK (difference_type IN ('EXCESS','SHORT','AMOUNT','STATUS','FEE')),
 CHECK ((reference_type IS NULL AND business_ref IS NULL) OR (reference_type IS NOT NULL AND reference_type IN ('PAYMENT_ATTEMPT','RECEIPT','REFUND') AND business_ref IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='交易侧渠道差异受理与处置关联，不负责账单比对';
CREATE TABLE tc_reconciliation_report_receipt (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '内部主键',
 tenant_id BIGINT UNSIGNED NOT NULL COMMENT '所属租户',
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '本地首次受理UTC时间',
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '最近状态变更UTC时间',
 version BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '并发版本',
 source_id VARCHAR(64) NOT NULL COMMENT '受信逻辑来源',
 event_id VARCHAR(128) NOT NULL COMMENT '来源永久事件键',
 request_hash CHAR(64) NOT NULL COMMENT '完整来源事件与业务正文摘要',
 case_no CHAR(36) NULL COMMENT '首次成功受理差异编号',
 accepted_at DATETIME(3) NULL COMMENT '首次成功受理UTC时间',
 PRIMARY KEY(id),
 UNIQUE KEY uk_recon_report(tenant_id,source_id,event_id),
 CHECK ((case_no IS NULL AND accepted_at IS NULL) OR (case_no IS NOT NULL AND accepted_at IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='对账报告永久幂等凭证，不依赖可淘汰命令缓存';
