ALTER TABLE tc_job_lease DROP CHECK chk_job_type,
 MODIFY COLUMN job_type VARCHAR(32) NOT NULL COMMENT '支付退款恢复回调补偿消息发布或独立对账查询任务类型',
 ADD CONSTRAINT chk_job_type CHECK (job_type IN ('PAYMENT_RECOVER','PAYMENT_CALLBACK','ORDER_RESOLVE','REFUND_CALLBACK','REFUND_RECOVER','REFUND_COMPENSATE','OUTBOX_PUBLISH','RECON_QUERY'));
CREATE TABLE tc_reconciliation_operation (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '内部操作主键',
 tenant_id BIGINT UNSIGNED NOT NULL COMMENT '所属可信租户',
 operation_no CHAR(36) NOT NULL COMMENT '永久查询操作UUID及任务业务键',
 actor_key CHAR(64) NOT NULL COMMENT '申请主体签发方与身份联合摘要',
 request_key VARCHAR(128) NOT NULL COMMENT '主体内永久请求幂等键',
 request_hash CHAR(64) NOT NULL COMMENT '完整查询申请摘要',
 case_no CHAR(36) NOT NULL COMMENT '被核对差异永久编号',
 action VARCHAR(32) NOT NULL COMMENT '仅查询原支付或原退款',
 reason VARCHAR(255) NOT NULL COMMENT '审计原因，不填写敏感原文',
 ticket_ref VARCHAR(128) NOT NULL COMMENT '外部工单引用，不表示已创建工单',
 channel_id BIGINT UNSIGNED NULL COMMENT '受理时冻结的原渠道绑定',
 reference_type VARCHAR(32) NULL COMMENT '原支付请求实收或资金退款引用类型',
 business_ref VARCHAR(64) NULL COMMENT '受理时冻结的原业务引用',
 case_version BIGINT UNSIGNED NULL COMMENT '首次受理后的差异版本',
 accepted_at DATETIME(3) NULL COMMENT '永久首次受理时间',
 status VARCHAR(24) NOT NULL DEFAULT 'QUEUED' COMMENT '排队执行证据已接收或待核对，不代表资金成功',
 last_code VARCHAR(64) NULL COMMENT '最近脱敏结果或错误分类',
 completed_at DATETIME(3) NULL COMMENT '本次操作达到终态的时间，不是差异结案时间',
 version BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '操作状态版本',
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '首次请求UTC时间',
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '最近更新UTC时间',
 PRIMARY KEY(id),
 UNIQUE KEY uk_recon_operation(tenant_id,operation_no),
 UNIQUE KEY uk_recon_operation_request(tenant_id,actor_key,request_key),
 KEY ix_recon_operation_queue(tenant_id,status,id),
 CHECK (action IN ('QUERY_PAYMENT','QUERY_REFUND')),
 CHECK (status IN ('QUEUED','RUNNING','RESULT_ACCEPTED','REVIEW')),
 CHECK ((accepted_at IS NULL AND case_version IS NULL AND channel_id IS NULL AND reference_type IS NULL AND business_ref IS NULL)
 OR (accepted_at IS NOT NULL AND case_version IS NOT NULL AND channel_id IS NOT NULL AND reference_type IS NOT NULL AND business_ref IS NOT NULL)),
 CHECK ((status IN ('QUEUED','RUNNING') AND completed_at IS NULL) OR (status IN ('RESULT_ACCEPTED','REVIEW') AND completed_at IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='对账独立查询永久回执及执行结果，不能自动关闭差异或执行收退款';
